"""Build the DuckDB database and export JSON for the website.

1. Load the CSVs from data/raw/ into tables.
2. Load AI drafts and their checks if they exist (data/ai/, data/check/).
3. Run every file in sql/ in filename order. Each file creates one view.
4. Export data/export/dashboard.json, the only file the website reads.

Run:  python build_db.py
"""

import json
from datetime import date
from decimal import Decimal
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parent
RAW = ROOT / "data" / "raw"
DB_PATH = ROOT / "data" / "runway.duckdb"
EXPORT = ROOT / "data" / "export" / "dashboard.json"
UPDATES = ROOT / "data" / "ai" / "updates.csv"
CHECKS = ROOT / "data" / "check" / "update_checks.csv"
ATTEMPTS = ROOT / "data" / "ai" / "update_attempts.csv"
RECON = ROOT / "data" / "check" / "reconciliation.json"

RAW_TABLES = ["customers", "mrr_movements", "headcount", "opex", "cash"]


def build(con, cutoff=None):
    """Load raw tables and create all views on connection `con`.

    cutoff (a 'YYYY-MM-01' string) keeps only data up to that month. Used by
    the look-ahead test in scripts/write_updates.py: 'pretend today is month m'.
    """
    for t in RAW_TABLES:
        con.execute(f"CREATE OR REPLACE TABLE {t} AS SELECT * FROM read_csv_auto('{(RAW / f'{t}.csv').as_posix()}')")
    if cutoff:
        c = f"DATE '{cutoff}'"
        for t in ["cash", "opex", "mrr_movements"]:
            con.execute(f"DELETE FROM {t} WHERE month > {c}")
        for t in ["customers", "headcount"]:
            con.execute(f"DELETE FROM {t} WHERE start_month > {c}")
            con.execute(f"UPDATE {t} SET end_month = NULL WHERE end_month > {c}")
    for f in sorted((ROOT / "sql").glob("*.sql")):
        con.execute(f.read_text(encoding="utf-8"))


def rows(con, sql):
    """Run a query and return a list of dicts with dates as 'YYYY-MM'."""
    cur = con.execute(sql)
    cols = [d[0] for d in cur.description]
    out = []
    for r in cur.fetchall():
        out.append({k: v.strftime("%Y-%m") if isinstance(v, date)
                    else float(v) if isinstance(v, Decimal) else v
                    for k, v in zip(cols, r)})
    return out


def export(con):
    monthly = rows(con, """
        SELECT s.*, b.opening_mrr, b.new_mrr, b.expansion_mrr, b.contraction_mrr, b.churn_mrr,
               b.closing_mrr, b.new_customers, b.churned_customers, b.active_customers,
               r.avg_net_burn_3m, r.runway_months, r.zero_cash_month,
               u.arr, u.arr_12m_ago, u.arr_growth_12m, u.nrr_12m, u.net_burn_3m,
               u.net_new_arr_3m, u.burn_multiple, u.burn_multiple_note
        FROM monthly_summary s
        JOIN mrr_bridge b USING (month)
        JOIN runway r USING (month)
        JOIN unit_metrics u USING (month)
        ORDER BY month""")
    data = {
        "company": "Nordlys Analytics ApS (fictional)",
        "note": "All data is synthetic. Generated by scripts/generate.py.",
        "monthly": monthly,
        "burn_drivers": rows(con, "SELECT * FROM burn_drivers ORDER BY month, driver_type, driver"),
        "hire_cost_by_team": rows(con, "SELECT * FROM hire_cost_by_team ORDER BY team"),
        "scenario_base": rows(con, "SELECT * FROM scenario_base")[0],
        "update_metrics": rows(con, "SELECT * FROM update_metrics ORDER BY month"),
        "updates": [],
        "update_checks": [],
        "update_attempts": [],
        "reconciliation": json.loads(RECON.read_text(encoding="utf-8")) if RECON.exists() else [],
    }
    tables = {r[0] for r in con.execute("SHOW TABLES").fetchall()}
    if "updates" in tables:
        data["updates"] = rows(con, """SELECT month, tldr, highlights, lowlights, ask, model, prompt_version,
                                               CAST(attempt AS INTEGER) AS attempt
                                        FROM updates ORDER BY month""")
    if "update_checks" in tables:
        data["update_checks"] = rows(con, "SELECT * FROM update_checks ORDER BY month")
    if "update_attempts" in tables:
        data["update_attempts"] = rows(con, """SELECT month, attempt, passed, checks_failed
                                                FROM update_attempts ORDER BY month, attempt""")
    EXPORT.parent.mkdir(parents=True, exist_ok=True)
    EXPORT.write_text(json.dumps(data, indent=1, ensure_ascii=False), encoding="utf-8")
    print(f"Exported {EXPORT.relative_to(ROOT)}: {len(monthly)} months, "
          f"{len(data['updates'])} updates, {len(data['update_checks'])} checks")


def main():
    DB_PATH.unlink(missing_ok=True)
    con = duckdb.connect(str(DB_PATH))
    build(con)
    # AI outputs are optional: they only exist after scripts/write_updates.py has run.
    # all_varchar keeps the text exactly as written (no type guessing).
    if UPDATES.exists():
        con.execute(f"CREATE TABLE updates AS SELECT * FROM read_csv('{UPDATES.as_posix()}', header=true, all_varchar=true)")
    if CHECKS.exists():
        con.execute(f"CREATE TABLE update_checks AS SELECT * FROM read_csv_auto('{CHECKS.as_posix()}')")
    if ATTEMPTS.exists():
        con.execute(f"CREATE TABLE update_attempts AS SELECT * FROM read_csv_auto('{ATTEMPTS.as_posix()}')")
    views = [r[0] for r in con.execute(
        "SELECT view_name FROM duckdb_views() WHERE NOT internal ORDER BY view_name").fetchall()]
    print("Views:", ", ".join(views))
    export(con)
    con.close()


if __name__ == "__main__":
    main()
