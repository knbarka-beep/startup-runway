import Link from "next/link";
import { data } from "@/lib/data";
import { eur, monthLabel, pct } from "@/lib/format";

export const metadata = { title: "How this works: Nordlys Analytics (fictional)" };

export default function Method() {
  const checks = data.update_checks;
  const nPass = checks.filter((c) => c.passed).length;
  const base = data.scenario_base;
  return (
    <main className="wrap method">
      <p><Link href="/">Back to the dashboard</Link></p>
      <h1>How this works</h1>

      <h2>The data is fictional</h2>
      <p>
        Nordlys Analytics ApS does not exist. Every customer, employee, cost and cash figure was generated by a Python
        script with a fixed random seed. Customer names are random combinations of invented word parts. The company is a
        Copenhagen B2B SaaS with a €3,0m seed round in Oct 2024, 15 employees growing to 25, and 24 months of data
        from Oct 2024 to Sep 2026. Some events were planted on purpose so there is a story to tell: a hiring push in
        spring 2026, the largest customer leaving in Jul 2026, a price increase on new contracts from Jun 2026, a strong
        expansion month in Nov 2025 and a one-off recruiting fee in Apr 2026.
      </p>

      <h2>Where the numbers come from</h2>
      <p>
        CSV files are loaded into DuckDB. Every metric is calculated once, in one SQL view per file. Those views are
        exported to a single JSON file, which is the only thing this website reads. The site makes no API calls.
      </p>

      <h2>Metric definitions</h2>
      <div className="table-scroll">
        <table>
          <thead><tr><th>Metric</th><th>Formula</th></tr></thead>
          <tbody>
            <tr><td>Cash in bank</td><td>Closing bank balance at month end</td></tr>
            <tr><td>Net burn</td><td>Payments minus collections in the month (funding excluded)</td></tr>
            <tr><td>Runway at current burn</td><td>Closing cash divided by the average net burn of the last 3 months</td></tr>
            <tr><td>Zero-cash month</td><td>The month cash would run out at that burn: this month plus runway, rounded up</td></tr>
            <tr><td>MRR</td><td>Monthly recurring revenue: the sum of all new, expansion, contraction and churn movements to date</td></tr>
            <tr><td>ARR</td><td>MRR x 12. Growth is compared with 12 months earlier</td></tr>
            <tr><td>Net revenue retention</td><td>MRR today from customers active 12 months ago, divided by their MRR then</td></tr>
            <tr><td>Burn multiple</td><td>Net burn over 3 months divided by net new ARR over the same 3 months. Left empty when ARR did not grow. It is high in Aug and Sep 2026 (7,1 and 12,3) because the largest customer churned in Jul 2026 and cancelled out most of the new ARR in those 3 months</td></tr>
            <tr><td>Gross margin</td><td>Revenue minus cost of revenue (cloud hosting plus customer success payroll), divided by revenue</td></tr>
          </tbody>
        </table>
      </div>

      <h2>Why runway uses a 3-month average</h2>
      <p>
        Annual customers pay 12 months upfront, so collections jump in renewal months. A single month of burn can even
        be negative. Averaging three months smooths that out but still reacts quickly to changes such as the spring
        2026 hiring push. Six or twelve months would hide that change for too long.
      </p>

      <h2>The scenario sliders</h2>
      <p>
        The dashed line starts from {monthLabel(base.start_month)} with {eur(base.start_cash)} in the bank and projects
        24 months. Each month: MRR grows by the growth rate and shrinks by the churn rate; cash changes by MRR minus
        payroll minus other costs plus any funding. Payroll starts at {eur(base.monthly_payroll)} a month and rises{" "}
        {pct(base.annual_salary_increase, 0)} every January (own assumption, for everyone including new hires). The page
        opens on the Current plan preset: growth {pct(base.default_growth_rate, 2)} and churn{" "}
        {pct(base.default_churn_rate, 2)} of MRR per month (12-month averages), other costs {eur(base.monthly_opex)} a
        month (3-month average), 2 full-time hires and 2 student assistants. Hiring push has 6 full-time hires; Downside
        has half the growth and 1,5 times the churn. A student assistant (part-time, about 15 hours a week) costs{" "}
        {eur(base.student_assistant_cost)} a month including holiday pay and starts in the first projected month. New
        hires add cost but do not change the growth rate, and customers are assumed to pay in the month revenue is
        earned. A full-time hire costs{" "}
        {eur(base.cost_per_hire)} a month: the average loaded cost per team, weighted by an assumed hiring mix of 40 %
        engineering, 35 % sales, 15 % customer success and 10 % G&amp;A. This is a tool for asking &quot;what if&quot;, not a
        forecast. A test checks that the browser calculation equals an independent Python version to within €1 a month.
      </p>

      <h2>What the AI does and does not do</h2>
      <p>
        For each month from Oct 2025 to Sep 2026 there is a draft investor update in five parts. The subject line and
        the key metrics table (cash, net burn, runway, MRR, ARR growth, customers and headcount, each with the change
        vs last month) are not written by AI: they come straight from the SQL views. Claude (model claude-sonnet-5-5,
        prompt v2) wrote the other three parts from a fact sheet of that month&apos;s numbers: a one-sentence TL;DR, up
        to two highlights and two lowlights, and one ask for investors. The fact sheet only contains data up to that
        month; a test rebuilds the database without the later months and confirms the input is identical. The text
        was generated once and stored. The website never calls the AI, and the sliders do not get AI text.
      </p>
      <p>
        <strong>These are drafts for a founder to finish.</strong> The data shows what happened, not why: it does not
        say why a customer left, what a professional fee was for or why someone was hired. Where such a reason
        matters, the AI was told to leave a placeholder such as &quot;[Founder: add reason]&quot; instead of guessing.
        The text is shown exactly as the model wrote it; there is no separate rewriting step.
      </p>
      <p>
        A script without AI then checks every draft. Each number must match a value in that month&apos;s data within
        the rounding the text uses. Causes the text names (for example churn or hiring) must be visible in the data;
        this is a crude keyword list. It also checks the structure (one TL;DR, one ask, at most two highlights and two
        lowlights, at least one lowlight when a key metric got worse, at most two numbers per highlight or lowlight)
        and a few style rules (at most 110 words, no banned filler words such as &quot;significant&quot; or
        &quot;robust&quot;, no em dashes, placeholders only in square brackets). None of this says anything about
        writing quality.
      </p>

      <h2>Check results</h2>
      <h3 className="small">Data reconciliation (raw data)</h3>
      <ul>
        {data.reconciliation.map((r) => (
          <li key={r.check}><span className={r.passed ? "" : "risk"}>{r.passed ? "PASS" : "FAIL"}</span> {r.check}</li>
        ))}
      </ul>
      <h3 className="small">AI update check</h3>
      {checks.length === 0 ? (
        <p className="muted">No AI drafts in this build.</p>
      ) : (
        <>
          <p>{nPass} of {checks.length} drafts pass all checks. The results are shown as the checker produced them;
            the drafts were not regenerated to make them pass.</p>
          <div className="table-scroll">
            <table>
              <thead><tr><th>Month</th><th>Numbers matched</th><th>Not matched</th><th>Words</th><th>Other problems</th><th>Result</th></tr></thead>
              <tbody>
                {checks.map((c) => (
                  <tr key={c.month}>
                    <td>{monthLabel(c.month)}</td>
                    <td>{c.numbers_matched} / {c.numbers_found}</td>
                    <td>{[c.unmatched_numbers, c.unsupported_causes].filter(Boolean).join("; ") || "none"}</td>
                    <td>{c.words}</td>
                    <td>{c.problems || "none"}</td>
                    <td className={c.passed ? "" : "risk"}>{c.passed ? "Pass" : "Flagged"}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
          <p className="muted small">
            How to read the flags: &quot;€128k&quot; for €128.684, &quot;€99k&quot; for €99.519 and &quot;€55k&quot; for
            €55.811 are rounding errors by the model (it cut the number off instead of rounding). &quot;100%&quot; is
            flagged because the checker only compares against data values, while 100 % appears in the fact sheet as the
            threshold (&quot;net revenue retention below 100 %&quot;); that is a limit of the checker, not a model error. The
            most common problem is three or four numbers in one highlight or lowlight, where the prompt asked for at most two.
          </p>
        </>
      )}

      <h2>Changes after the first run</h2>
      <ul>
        <li>
          The checker has been revised twice, both times for false flags, and both changes are listed in
          docs/decisions.md. First, after the first run, it wrongly flagged 4 correct drafts that said &quot;lost
          none&quot; or &quot;Nothing churned&quot;. Second, in review round 2, it flagged &quot;100 %&quot; four times in
          the v2 drafts: that number comes from our own rule about net revenue retention below 100 %, not from the
          data, so 100 followed by % is now skipped like the constants 3 and 12. Each fix has a case in the
          checker&apos;s self-test.
        </li>
        <li>
          The update format was changed once after reviewing two v1 drafts (Apr and Jul 2026): they were too dense,
          with 20 or more numbers in running prose, and had no ask. The v2 format is the five parts above. The v1
          drafts are kept in data/ai/updates_v1.csv.
        </li>
      </ul>

      <h2>Limitations</h2>
      <ul>
        <li>All data is synthetic, so the patterns are only as realistic as the assumptions behind them.</li>
        <li>Revenue equals MRR. No proration, VAT, tax, payables or receivables timing.</li>
        <li>The projection keeps other costs flat apart from the slider, treats collections as equal to revenue (annual upfront billing is ignored) and does not let new hires change the growth rate.</li>
        <li>Gross margin counts cloud hosting and customer success payroll as cost of revenue. Third-party software stays in operating costs because the data does not say which part serves customers.</li>
        <li>The AI check verifies numbers, named causes, structure and a few style rules. A draft could pass and still be badly written or emphasise the wrong thing, and every draft needs a founder to fill in the placeholders.</li>
      </ul>
    </main>
  );
}
